package com.scanr.app.export

import com.scanr.app.data.MeshData
import com.scanr.app.data.PointCloud
import com.scanr.app.data.Vector3
import com.scanr.app.data.Vertex
import java.io.BufferedWriter
import java.io.OutputStream
import java.io.OutputStreamWriter
import java.util.Locale

class PlyExporter : MeshExporter {
    
    override val format = ExportFormat.PLY
    
    override fun export(
        meshData: MeshData,
        outputStream: OutputStream,
        options: ExportOptions
    ): ExportResult {
        return try {
            val writer = BufferedWriter(OutputStreamWriter(outputStream, Charsets.UTF_8))
            var bytesWritten = 0L
            
            val vertices = if (options.centerModel) {
                centerVertices(meshData.vertices, meshData.boundingBoxCenter)
            } else {
                meshData.vertices
            }
            
            bytesWritten += writeHeader(
                writer,
                vertices.size,
                meshData.triangles.size,
                options.includeNormals,
                options.includeColors
            )
            
            bytesWritten += writeVertices(writer, vertices, options)
            
            bytesWritten += writeFaces(writer, meshData)
            
            writer.flush()
            writer.close()
            
            ExportResult(
                success = true,
                format = format,
                vertexCount = vertices.size,
                faceCount = meshData.triangles.size,
                fileSizeBytes = bytesWritten
            )
        } catch (e: Exception) {
            ExportResult(
                success = false,
                format = format,
                vertexCount = 0,
                faceCount = 0,
                fileSizeBytes = 0,
                errorMessage = e.message
            )
        }
    }
    
    override fun export(
        pointCloud: PointCloud,
        outputStream: OutputStream,
        options: ExportOptions
    ): ExportResult {
        return try {
            val writer = BufferedWriter(OutputStreamWriter(outputStream, Charsets.UTF_8))
            var bytesWritten = 0L
            
            val vertices = if (options.centerModel) {
                centerVertices(pointCloud.points, pointCloud.boundingBoxCenter)
            } else {
                pointCloud.points
            }
            
            bytesWritten += writeHeader(
                writer,
                vertices.size,
                0,
                options.includeNormals,
                options.includeColors
            )
            
            bytesWritten += writeVertices(writer, vertices, options)
            
            writer.flush()
            writer.close()
            
            ExportResult(
                success = true,
                format = format,
                vertexCount = vertices.size,
                faceCount = 0,
                fileSizeBytes = bytesWritten
            )
        } catch (e: Exception) {
            ExportResult(
                success = false,
                format = format,
                vertexCount = 0,
                faceCount = 0,
                fileSizeBytes = 0,
                errorMessage = e.message
            )
        }
    }
    
    private fun writeHeader(
        writer: BufferedWriter,
        vertexCount: Int,
        faceCount: Int,
        includeNormals: Boolean,
        includeColors: Boolean
    ): Long {
        val header = buildString {
            appendLine("ply")
            appendLine("format ascii 1.0")
            appendLine("comment Generated by ScanR App")
            appendLine("comment https://github.com/scanr")
            appendLine("element vertex $vertexCount")
            appendLine("property float x")
            appendLine("property float y")
            appendLine("property float z")
            if (includeNormals) {
                appendLine("property float nx")
                appendLine("property float ny")
                appendLine("property float nz")
            }
            if (includeColors) {
                appendLine("property uchar red")
                appendLine("property uchar green")
                appendLine("property uchar blue")
            }
            appendLine("property float confidence")
            if (faceCount > 0) {
                appendLine("element face $faceCount")
                appendLine("property list uchar int vertex_indices")
            }
            appendLine("end_header")
        }
        writer.write(header)
        return header.length.toLong()
    }
    
    private fun writeVertices(
        writer: BufferedWriter,
        vertices: List<Vertex>,
        options: ExportOptions
    ): Long {
        var bytesWritten = 0L
        val scale = options.scale
        
        vertices.forEach { vertex ->
            val pos = vertex.position
            val (x, y, z) = if (options.flipYZ) {
                Triple(pos.x * scale, pos.z * scale, -pos.y * scale)
            } else {
                Triple(pos.x * scale, pos.y * scale, pos.z * scale)
            }
            
            val line = buildString {
                append("${formatFloat(x)} ${formatFloat(y)} ${formatFloat(z)}")
                
                if (options.includeNormals) {
                    val normal = vertex.normal
                    val (nx, ny, nz) = if (options.flipYZ) {
                        Triple(normal.x, normal.z, -normal.y)
                    } else {
                        Triple(normal.x, normal.y, normal.z)
                    }
                    append(" ${formatFloat(nx)} ${formatFloat(ny)} ${formatFloat(nz)}")
                }
                
                if (options.includeColors) {
                    val color = vertex.color
                    if (color != null) {
                        val r = (color.r * 255).toInt().coerceIn(0, 255)
                        val g = (color.g * 255).toInt().coerceIn(0, 255)
                        val b = (color.b * 255).toInt().coerceIn(0, 255)
                        append(" $r $g $b")
                    } else {
                        append(" 200 200 200")
                    }
                }
                
                append(" ${formatFloat(vertex.confidence)}")
                appendLine()
            }
            
            writer.write(line)
            bytesWritten += line.length
        }
        
        return bytesWritten
    }
    
    private fun writeFaces(writer: BufferedWriter, meshData: MeshData): Long {
        var bytesWritten = 0L
        
        meshData.triangles.forEach { triangle ->
            val line = "3 ${triangle.v0} ${triangle.v1} ${triangle.v2}\n"
            writer.write(line)
            bytesWritten += line.length
        }
        
        return bytesWritten
    }
    
    private fun centerVertices(vertices: List<Vertex>, center: Vector3): List<Vertex> {
        return vertices.map { vertex ->
            vertex.copy(position = vertex.position - center)
        }
    }
    
    private fun formatFloat(value: Float): String {
        return String.format(Locale.US, "%.6f", value)
    }
}
