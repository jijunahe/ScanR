package com.scanr.app.export

import com.scanr.app.data.MeshData
import com.scanr.app.data.PointCloud
import com.scanr.app.data.Vector3
import com.scanr.app.data.Vertex
import java.io.BufferedWriter
import java.io.OutputStream
import java.io.OutputStreamWriter
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

class ObjExporter : MeshExporter {
    
    override val format = ExportFormat.OBJ
    
    override fun export(
        meshData: MeshData,
        outputStream: OutputStream,
        options: ExportOptions
    ): ExportResult {
        return try {
            val writer = BufferedWriter(OutputStreamWriter(outputStream, Charsets.UTF_8))
            var bytesWritten = 0L
            
            val vertices = if (options.centerModel) {
                centerVertices(meshData.vertices, meshData.boundingBoxCenter)
            } else {
                meshData.vertices
            }
            
            bytesWritten += writeHeader(writer, options, vertices.size, meshData.triangles.size)
            
            bytesWritten += writeVertices(writer, vertices, options)
            
            if (options.includeNormals) {
                bytesWritten += writeNormals(writer, vertices, options)
            }
            
            bytesWritten += writeFaces(writer, meshData.triangles.size, options.includeNormals)
            
            writer.flush()
            writer.close()
            
            ExportResult(
                success = true,
                format = format,
                vertexCount = vertices.size,
                faceCount = meshData.triangles.size,
                fileSizeBytes = bytesWritten
            )
        } catch (e: Exception) {
            ExportResult(
                success = false,
                format = format,
                vertexCount = 0,
                faceCount = 0,
                fileSizeBytes = 0,
                errorMessage = e.message
            )
        }
    }
    
    override fun export(
        pointCloud: PointCloud,
        outputStream: OutputStream,
        options: ExportOptions
    ): ExportResult {
        return try {
            val writer = BufferedWriter(OutputStreamWriter(outputStream, Charsets.UTF_8))
            var bytesWritten = 0L
            
            val vertices = if (options.centerModel) {
                centerVertices(pointCloud.points, pointCloud.boundingBoxCenter)
            } else {
                pointCloud.points
            }
            
            bytesWritten += writeHeader(writer, options, vertices.size, 0)
            
            bytesWritten += writeVertices(writer, vertices, options)
            
            if (options.includeNormals) {
                bytesWritten += writeNormals(writer, vertices, options)
            }
            
            writer.flush()
            writer.close()
            
            ExportResult(
                success = true,
                format = format,
                vertexCount = vertices.size,
                faceCount = 0,
                fileSizeBytes = bytesWritten
            )
        } catch (e: Exception) {
            ExportResult(
                success = false,
                format = format,
                vertexCount = 0,
                faceCount = 0,
                fileSizeBytes = 0,
                errorMessage = e.message
            )
        }
    }
    
    private fun writeHeader(
        writer: BufferedWriter,
        options: ExportOptions,
        vertexCount: Int,
        faceCount: Int
    ): Long {
        val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)
        val header = buildString {
            appendLine("# Wavefront OBJ File")
            appendLine("# Generated by ${options.authorName}")
            appendLine("# Date: ${dateFormat.format(Date())}")
            appendLine("# Vertices: $vertexCount")
            appendLine("# Faces: $faceCount")
            appendLine("#")
            appendLine("o ${options.objectName}")
            appendLine()
        }
        writer.write(header)
        return header.length.toLong()
    }
    
    private fun writeVertices(
        writer: BufferedWriter,
        vertices: List<Vertex>,
        options: ExportOptions
    ): Long {
        var bytesWritten = 0L
        val scale = options.scale
        
        vertices.forEach { vertex ->
            val pos = vertex.position
            val (x, y, z) = if (options.flipYZ) {
                Triple(pos.x * scale, pos.z * scale, -pos.y * scale)
            } else {
                Triple(pos.x * scale, pos.y * scale, pos.z * scale)
            }
            
            val line = "v ${formatFloat(x)} ${formatFloat(y)} ${formatFloat(z)}\n"
            writer.write(line)
            bytesWritten += line.length
        }
        
        writer.write("\n")
        bytesWritten += 1
        
        return bytesWritten
    }
    
    private fun writeNormals(
        writer: BufferedWriter,
        vertices: List<Vertex>,
        options: ExportOptions
    ): Long {
        var bytesWritten = 0L
        
        vertices.forEach { vertex ->
            val normal = vertex.normal
            val (nx, ny, nz) = if (options.flipYZ) {
                Triple(normal.x, normal.z, -normal.y)
            } else {
                Triple(normal.x, normal.y, normal.z)
            }
            
            val line = "vn ${formatFloat(nx)} ${formatFloat(ny)} ${formatFloat(nz)}\n"
            writer.write(line)
            bytesWritten += line.length
        }
        
        writer.write("\n")
        bytesWritten += 1
        
        return bytesWritten
    }
    
    private fun writeFaces(
        writer: BufferedWriter,
        faceCount: Int,
        includeNormals: Boolean
    ): Long {
        var bytesWritten = 0L
        
        for (i in 0 until faceCount) {
            val v1 = i * 3 + 1
            val v2 = i * 3 + 2
            val v3 = i * 3 + 3
            
            val line = if (includeNormals) {
                "f $v1//$v1 $v2//$v2 $v3//$v3\n"
            } else {
                "f $v1 $v2 $v3\n"
            }
            writer.write(line)
            bytesWritten += line.length
        }
        
        return bytesWritten
    }
    
    private fun centerVertices(vertices: List<Vertex>, center: Vector3): List<Vertex> {
        return vertices.map { vertex ->
            vertex.copy(position = vertex.position - center)
        }
    }
    
    private fun formatFloat(value: Float): String {
        return String.format(Locale.US, "%.6f", value)
    }
}
